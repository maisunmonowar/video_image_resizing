import argparse
import os
import re
import sys
import subprocess
import tempfile
from datetime import datetime
from pathlib import Path


SOURCE_LANGUAGES = {
    ".c": "c",
    ".cc": "cpp",
    ".cpp": "cpp",
    ".cs": "csharp",
    ".cxx": "cpp",
    ".go": "go",
    ".h": "c",
    ".hh": "cpp",
    ".hpp": "cpp",
    ".hxx": "cpp",
    ".java": "java",
    ".js": "javascript",
    ".jsx": "jsx",
    ".kt": "kotlin",
    ".lua": "lua",
    ".m": "objective-c",
    ".mm": "objective-cpp",
    ".php": "php",
    ".py": "python",
    ".r": "r",
    ".rb": "ruby",
    ".rs": "rust",
    ".scala": "scala",
    ".sh": "bash",
    ".sql": "sql",
    ".swift": "swift",
    ".ts": "typescript",
    ".tsx": "tsx",
    ".vue": "vue",
}

MAX_FILE_SIZE = 1_000_000


def is_readme(path):
    return path.name.lower().startswith("readme") and path.suffix.lower() in {
        ".md",
        ".markdown",
        ".rst",
        ".txt",
    }


def language_for(path):
    if is_readme(path):
        return "markdown"
    return SOURCE_LANGUAGES.get(path.suffix.lower())


def repository_root(path):
    result = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "--show-toplevel"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        detail = result.stderr.decode(errors="replace").strip()
        message = f"Not inside a Git repository: {path}"
        raise ValueError(message + (f"\n{detail}" if detail else ""))
    top_level = result.stdout.rstrip(b"\r\n")
    return Path(os.fsdecode(top_level)).resolve()


def collect_files(root):
    root = repository_root(Path(root).resolve())
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode:
        detail = result.stderr.decode(errors="replace").strip()
        message = f"Could not list tracked files in {root}"
        raise ValueError(message + (f"\n{detail}" if detail else ""))

    selected = []
    for entry in result.stdout.split(b"\0"):
        if not entry:
            continue
        path = root / os.fsdecode(entry)
        if language_for(path) is None:
            continue
        if path.name.lower().endswith((".min.js", ".min.css")):
            continue
        try:
            if not path.is_file() or path.stat().st_size > MAX_FILE_SIZE:
                continue
        except OSError:
            continue
        selected.append(path)

    return sorted(selected, key=lambda path: path.relative_to(root).as_posix().lower())


def fenced_block(content, language):
    longest_backtick_run = max(
        (len(match.group(0)) for match in re.finditer(r"`+", content)), default=0
    )
    fence = "`" * max(3, longest_backtick_run + 1)
    body = content.rstrip("\r\n")
    return f"{fence}{language}\n{body}\n{fence}"


def build_reference(root, files):
    root = Path(root).resolve()
    relative_paths = [path.relative_to(root).as_posix() for path in files]
    lines = [
        f"# Project reference: {root.name}",
        "",
        f"Generated: {datetime.now().astimezone().isoformat(timespec='seconds')}",
        f"Project root: `{root}`",
        "",
        "This file is generated by `code_compactor.py`. Run it again to create a new snapshot.",
        "",
        "## Contents",
        "",
    ]

    if not files:
        lines.append("_No supported source files, README files, or test files were found._")
    else:
        for index, relative_path in enumerate(relative_paths, start=1):
            anchor = re.sub(r"[^a-z0-9 -]", "", relative_path.lower()).replace(" ", "-")
            lines.append(f"{index}. [{relative_path}](#{anchor})")
        for path, relative_path in zip(files, relative_paths):
            language = language_for(path)
            content = path.read_text(encoding="utf-8-sig", errors="replace")
            lines.extend(
                [
                    "",
                    f"## {relative_path}",
                    "",
                    fenced_block(content, language),
                ]
            )

    return "\n".join(lines) + "\n"


def default_output_path(root):
    desktop = Path.home() / "Desktop"
    output_directory = desktop / "temp"
    timestamp = datetime.now().astimezone().strftime("%Y%m%d_%H%M%S_%f")
    return output_directory / f"{Path(root).resolve().name}_reference_{timestamp}.md"


def available_output_path(path):
    path = Path(path)
    if not path.exists():
        return path
    index = 2
    while True:
        candidate = path.with_name(f"{path.stem}_{index}{path.suffix}")
        if not candidate.exists():
            return candidate
        index += 1


def write_reference(root, output_path=None):
    root = Path(root).expanduser().resolve()
    if not root.is_dir():
        raise ValueError(f"Project folder does not exist: {root}")
    root = repository_root(root)
    output_path = Path(output_path).expanduser() if output_path else default_output_path(root)
    output_path = available_output_path(output_path.resolve())
    if output_path == root or root in output_path.parents:
        raise ValueError("Choose an output path outside the project folder.")

    files = collect_files(root)
    document = build_reference(root, files)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=output_path.parent,
            prefix=f".{output_path.name}.",
            suffix=".tmp",
            delete=False,
        ) as temporary_file:
            temporary_path = Path(temporary_file.name)
            temporary_file.write(document)
        temporary_path.replace(output_path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()

    return output_path, len(files)


def run_gui():
    import tkinter as tk
    from tkinter import filedialog, messagebox

    window = tk.Tk()
    window.withdraw()
    root = filedialog.askdirectory(title="Choose the project to document")
    if not root:
        return 0

    try:
        output_path, count = write_reference(root)
    except (OSError, ValueError) as error:
        messagebox.showerror("Reference document not updated", str(error))
        return 1

    messagebox.showinfo(
        "Reference document updated",
        f"Included {count} files.\n\nSaved to:\n{output_path}",
    )
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=(
            "Create or refresh a Markdown reference document from source, "
            "README, and test files in a project."
        )
    )
    parser.add_argument(
        "--root",
        help="Project folder to scan. Without this option, a folder picker opens.",
    )
    parser.add_argument(
        "--output",
        help=(
            "Output Markdown path. Defaults to a timestamped file in Desktop/temp; "
            "existing paths are never overwritten."
        ),
    )
    args = parser.parse_args(argv)

    if not args.root:
        if args.output:
            parser.error("--output requires --root.")
        return run_gui()

    root = Path(args.root).expanduser()
    output_path = Path(args.output).expanduser() if args.output else None
    try:
        output_path, count = write_reference(root, output_path)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    print(f"Created {output_path} with {count} tracked files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
